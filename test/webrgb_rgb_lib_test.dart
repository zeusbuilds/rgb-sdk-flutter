import 'dart:convert';

import 'package:flutter/services.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:rgb_sdk_flutter/rgb_sdk_flutter.dart';
import 'package:rgb_sdk_flutter/rgb_sdk_flutter_webrgb.dart';

import 'burn_operations_test.dart' show MemoryBurnStore;

const _channel = MethodChannel('com.utexo.rgb_sdk_flutter/rgb_lib');
const _assetId = 'rgb:asset';
const _payout = BurnPayout(
  chainId: 'eip155:42161',
  address: '0x1111111111111111111111111111111111111111',
);
const _commitment =
    '65101fb7d644f69b71360617954850e0c357789253eb373dde3f0d9077f2fbc7';
final _txid = 'ab' * 32;

void main() {
  final messenger =
      TestWidgetsFlutterBinding.ensureInitialized().defaultBinaryMessenger;

  test('V1 commitment matches the upstream independent ABI vectors', () {
    // Upstream fixtures were generated by go-ethereum accounts/abi.
    final direct = BurnDestination.forPayout(
      BurnDestinationRoute(chainId: _payout.chainId, dstEid: 0),
      _payout.address,
    );
    expect(direct.commitment, _commitment);
    final tron = BurnDestination.fromJson({
      'version': 1,
      'destinationChainId': 728126428,
      'dstEid': 30420,
      'recipient': '0x413333333333333333333333333333333333333333',
    });
    expect(
      tron.commitment,
      '60c369ce30870783c2a8cee9e6018e78650ad4787c2e898c05c35cb85179eac0',
    );
  });

  test(
    'RGB_L1 binds approved V1 routes to a durable burn and proof consent',
    () async {
      final calls = <MethodCall>[];
      messenger.setMockMethodCallHandler(_channel, (call) async {
        calls.add(call);
        return _nativeReply(call.method);
      });
      addTearDown(() => messenger.setMockMethodCallHandler(_channel, null));
      RgbLibWallet wallet() => RgbLibWallet(
        params: const RgbLibWalletParams(
          network: 'mainnet',
          storageDirPath: '/private/test',
        ),
        keys: RgbLibKeys.mnemonic('test-only fixture'),
      );

      final store = MemoryBurnStore();
      final routes = [
        BurnDestinationRoute(chainId: _payout.chainId, dstEid: 0),
      ];
      final prompts = <WebRgbApproval>[];
      var consent = true;
      WebRgbProvider provider(RgbLibWallet native, String origin) =>
          WebRgbProvider.rgbLib(
            native,
            WebRgbOptions(
              origin: origin,
              sessionApproved: true,
              confirm: (approval) async {
                prompts.add(approval);
                return consent;
              },
              burn: WebRgbBurnOptions(
                operations: BurnOperations(native, store),
                allowedPayoutChainIds: [_payout.chainId],
                destinationRoutes: routes,
              ),
            ),
          );

      final native = wallet();
      await native.init();
      final current = provider(native, 'https://wallet.example');
      final info = await current.getInfo();
      expect(info.protocol, 'RGB_L1');
      expect(info.methods, contains('burnAsset'));
      expect(info.methods, isNot(contains('signMessage')));
      expect(info.toJson()['burnDestinationRoutes'], [routes.single.toJson()]);

      WebRgbBurnAssetArgs request([BurnDestination? destination]) =>
          WebRgbBurnAssetArgs(
            network: 'mainnet',
            assetId: _assetId,
            amount: '5',
            burnRecipient: _payout,
            burnDestination: destination,
          );
      final expected = BurnDestination.forPayout(
        routes.single,
        _payout.address,
      );
      final altered = BurnDestination.fromJson({
        ...expected.toJson(),
        'dstEid': 1,
      });
      await expectLater(
        current.burnAsset(request(altered)),
        _error('INVALID_PARAMS'),
      );
      expect(prompts, isEmpty);
      expect(store.writes, isEmpty);
      expect(calls.where((call) => call.method == 'burn'), isEmpty);

      final result = await current.burnAsset(request());
      expect(result.burnDestination?.toJson(), expected.toJson());
      expect(prompts.single.params['burnDestination'], expected.toJson());
      expect(
        calls
            .singleWhere((call) => call.method == 'burn')
            .arguments['burnReason'],
        _commitment,
      );
      expect(store.writes, [
        BurnOperationState.prepared,
        BurnOperationState.pending,
        BurnOperationState.complete,
      ]);
      current.revoke();
      await native.destroy();

      final reopened = wallet();
      await reopened.init();
      final operations = BurnOperations(reopened, store);
      final record = (await operations.records()).single;
      expect(record.metadata.burnDestination?.toJson(), expected.toJson());
      final badRecord =
          jsonDecode(jsonEncode(record.toJson())) as Map<String, dynamic>;
      (badRecord['metadata']['burnDestination'] as Map)['dstEid'] = 1;
      expect(
        () => normalizeBurnRecord(badRecord),
        throwsA(isA<WalletValidationException>()),
      );

      final bridge = provider(reopened, 'https://bridge.example');
      final proofArgs = WebRgbGetConsignmentArgs(
        assetId: _assetId,
        txid: _txid,
      );
      consent = false;
      await expectLater(
        bridge.getConsignment(proofArgs),
        _error('USER_REJECTED'),
      );
      expect(
        (await bridge.getTransferStatus(
          _txid,
          _assetId,
        )).transfer?.burnDestination,
        isNull,
      );
      consent = true;
      expect((await bridge.getConsignment(proofArgs)).data, 'YWJj');
      final status = (await bridge.getTransferStatus(
        _txid,
        _assetId,
      )).transfer!;
      expect(status.burnDestination?.toJson(), expected.toJson());
      expect(status.blockHeight, 100);
      expect(status.confirmations, isNull);
      expect(calls.where((call) => call.method == 'burn'), hasLength(1));
      await reopened.destroy();
    },
  );
}

Matcher _error(String code) =>
    throwsA(isA<WebRgbError>().having((e) => e.code, 'code', code));

